#!/usr/bin/env python3
"""Generates fresco_test_images.hpp: small PNGs written by Python's zlib (an encoder that shares no code with the C++ decoder).

Pixel (x, y, channel c) = (7x + 13y + 50c) mod 256 over a 37 x 23 picture (odd sizes on purpose). Run: make_test_images.py > fresco_test_images.hpp
"""
import struct, zlib, sys

W, H = 37, 23
def val(x, y, c): return (7 * x + 13 * y + 50 * c) % 256

def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

def paeth(a, b, c):
    p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return a if pa <= pb and pa <= pc else (b if pb <= pc else c)

def filt(raw, prev, bpp, f):
    out = bytearray([f])
    for i, v in enumerate(raw):
        a = raw[i - bpp] if i >= bpp else 0
        b = prev[i]
        c = prev[i - bpp] if i >= bpp else 0
        if f == 0: p = 0
        elif f == 1: p = a
        elif f == 2: p = b
        elif f == 3: p = (a + b) // 2
        else: p = paeth(a, b, c)
        out.append((v - p) & 255)
    return bytes(out)

def png(colour, depth, rows, plte=None, strategy=None, level=9, cycle=True):
    stride = len(rows[0]); bpp = max(1, (len(rows[0]) // W) if depth >= 8 else 1)
    if depth >= 8:
        bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[colour] * (depth // 8)
    prev = bytes(stride); data = b""
    for y, r in enumerate(rows):
        data += filt(r, prev, bpp, y % 5 if cycle else 0); prev = r
    co = zlib.compressobj(level, zlib.DEFLATED, 15, 8, strategy if strategy is not None else zlib.Z_DEFAULT_STRATEGY)
    z = co.compress(data) + co.flush()
    out = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, depth, colour, 0, 0, 0))
    if plte: out += chunk(b"PLTE", plte)
    return out + chunk(b"IDAT", z) + chunk(b"IEND", b"")

def png_adam7_gray8():
    passes = ((0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4),
              (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2))
    data = b""
    for pass_index, (x0, y0, dx, dy) in enumerate(passes):
        xs = range(x0, W, dx)
        prev = bytes(len(xs))
        for pass_y, y in enumerate(range(y0, H, dy)):
            raw = bytes(val(x, y, 0) for x in xs)
            data += filt(raw, prev, 1, (pass_index + pass_y) % 5)
            prev = raw
    z = zlib.compress(data)
    return (b"\x89PNG\r\n\x1a\n" +
            chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 1)) +
            chunk(b"IDAT", z) + chunk(b"IEND", b""))

def pack(bits, samples):
    out = bytearray(); acc = 0; n = 0
    for s in samples:
        acc = (acc << bits) | s; n += bits
        if n == 8: out.append(acc); acc = 0; n = 0
    if n: out.append(acc << (8 - n))
    return bytes(out)

images = {}
images["gray8"] = png(0, 8, [bytes(val(x, y, 0) for x in range(W)) for y in range(H)])
images["rgb8"] = png(2, 8, [bytes(val(x, y, c) for x in range(W) for c in range(3)) for y in range(H)])
images["rgb8_fixed"] = png(2, 8, [bytes(val(x, y, c) for x in range(W) for c in range(3)) for y in range(H)], strategy=zlib.Z_FIXED)
images["rgb8_stored"] = png(2, 8, [bytes(val(x, y, c) for x in range(W) for c in range(3)) for y in range(H)], level=0)
images["rgba8"] = png(6, 8, [bytes(v for x in range(W) for v in (val(x, y, 0), val(x, y, 1), val(x, y, 2), 128)) for y in range(H)])
images["gray16"] = png(0, 16, [b"".join(bytes([val(x, y, 0), 77]) for x in range(W)) for y in range(H)])
images["graya8"] = png(4, 8, [bytes(v for x in range(W) for v in (val(x, y, 0), 255)) for y in range(H)])
# palette: 16 entries, entry i = (i*16, 255 - i*16, i*5), 4-bit indices (x + y) mod 16
pal = b"".join(bytes([i * 16, 255 - i * 16, i * 5]) for i in range(16))
images["pal4"] = png(3, 4, [pack(4, [(x + y) % 16 for x in range(W)]) for y in range(H)], plte=pal)
images["gray1"] = png(0, 1, [pack(1, [(x * 3 + y) % 2 for x in range(W)]) for y in range(H)])
images["gray8_adam7"] = png_adam7_gray8()

print("// Generated by make_test_images.py: do not edit.\n#pragma once\n#include <cstdint>\n#include <vector>\nnamespace fresco_test {")
print("struct Named { const char* name; std::vector<std::uint8_t> bytes; };")
print("inline const std::vector<Named>& pngs() {\n  static const std::vector<Named> v = {")
for k, d in images.items():
    print('    {"%s", {%s}},' % (k, ",".join(str(b) for b in d)))
print("  };\n  return v;\n}\n}  // namespace fresco_test")
